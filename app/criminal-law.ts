    if (k === "287-2") return clause("287-2", `《中华人民共和国刑法》第二百八十七条之二【帮助信息网络犯罪活动罪】`);
    if (k === "312") return clause("312", `《中华人民共和国刑法》第三百一十二条【掩饰、隐瞒犯罪所得、犯罪所得收益罪】`);
    if (k === "372") return clause("372", `《中华人民共和国刑法》第三百七十二条【冒充军人招摇撞骗罪】`);
    if (k === "279") return clause("279", `《中华人民共和国刑法》第二百七十九条【招摇撞骗罪】`);
    if (k === "253-1") return clause("253-1", `《中华人民共和国刑法》第二百五十三条之一【侵犯公民个人信息罪】`);
